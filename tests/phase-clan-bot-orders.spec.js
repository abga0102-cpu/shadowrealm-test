const assert=require('node:assert/strict');
const C=require('../clan-bot-sandbox.js');
const W=require('../clan-war-rules.js');
const custom=C.create(C.fresh(),'Le Cercle','🐉').state;
const roster=C.myClan(custom).members.filter(x=>x.kind==='bot');
assert.equal(roster.length,8);
let s=C.sanitizeOrders(null,'custom');
assert.equal(s.day,1);
assert.equal(C.setOrder(s,'custom','false').ok,false);
assert.equal(C.setOrder(s,'custom','rest','bot:aube:0').ok,false);
assert.equal(C.chooseDay(s,'custom',99).ok,false);
s=C.setOrder(s,'custom','attack').state;
assert.equal(C.runRound(s,'custom',W).acted,0,'assaults cannot happen day 1');
s=C.chooseDay(s,'custom',6).state;
for(let i=0;i<5;i++){const result=C.runRound(s,'custom',W);assert.equal(result.acted,8);s=result.state;}
assert.equal(C.runRound(s,'custom',W).acted,0,'5 tickets limit');
assert.ok(C.commandStats(s,'custom').bots.every(b=>b.attacks===5));
assert.equal(C.commandStats(s,'custom').total,40);
assert.equal(s.journal.length,36,'bounded journal');
assert.equal(C.sanitizeOrders(s,'nord').global,'auto','orders cannot cross clan boundary');
s=C.chooseDay(s,'custom',1).state;
s=C.setOrder(s,'custom','save').state;assert.equal(C.runRound(s,'custom',W).acted,0);
s=C.setOrder(s,'custom','auto').state;
s=C.setOrder(s,'custom','rest',roster[0].id).state;
assert.equal(C.runRound(s,'custom',W).acted,7,'individual bot obeys rest');
assert.equal(C.setOrder(s,'custom','inherit',roster[0].id).state.perBot[roster[0].id],undefined);
assert.equal(C.runRound(C.chooseDay(s,'custom',7).state,'custom',W).ok,false);
const damaged=C.sanitizeOrders({version:1,clanId:'custom',day:500,global:'invalid',perBot:{'bot:custom:0':'save','bot:aube:0':'save'},counts:{'bot:custom:0':[999,-4,1.3,1,0,80]},journal:[{id:'bot:aube:0',day:6,action:'clan_attack',points:4}]},'custom');
assert.equal(damaged.day,1);assert.equal(damaged.global,'auto');
assert.equal(damaged.counts['bot:custom:0'][0],8);assert.equal(damaged.counts['bot:custom:0'][5],5);
assert.equal(damaged.journal.length,0);
const db={'shadowreach.save.local':'DO NOT TOUCH'},keys=[];
const storage={getItem:k=>(keys.push(k),db[k]),setItem:(k,v)=>(keys.push(k),db[k]=v),removeItem:k=>(keys.push(k),delete db[k])};
assert.equal(C.writeOrders(storage,'custom',s),true);
assert.equal(C.readOrders(storage,'custom').day,1);
assert.equal(C.clearOrders(storage),true);
assert.equal(db['shadowreach.save.local'],'DO NOT TOUCH');
assert.ok(keys.every(k=>k===C.ORDERS_KEY));
assert.equal(C.writeOrders({setItem(){throw Error('full')}},'custom',s),false);
assert.equal(C.readOrders({getItem(){throw Error('blocked')}},'custom').global,'auto');
assert.equal(C.clearOrders({removeItem(){throw Error('blocked')} }),false);
assert.equal(C.resetRounds(s,'custom').state.journal.length,0);
