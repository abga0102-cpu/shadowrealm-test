const {test,expect}=require('@playwright/test');
test('bots obey collective and individual orders, save without altering game progress',async({page})=>{
 await page.goto('/clan-bots-preview.html');
 await page.evaluate(()=>localStorage.setItem('shadowreach.save.local','SAFE'));
 await page.locator('#joinClan').click();
 await page.locator('[data-tab="orders"]').click();
 await expect(page.locator('[data-bot-command]')).toHaveCount(12);
 await page.locator('[data-command="save"]').click();
 await page.locator('#runOrders').click();
 await expect(page.locator('#status')).toContainText('0 bots');
 await page.locator('[data-command="auto"]').click();
 await page.locator('[data-bot-command]').first().selectOption('rest');
 await page.locator('#runOrders').click();
 await expect(page.locator('#status')).toContainText('11 bots');
 await page.reload();await page.locator('[data-tab="orders"]').click();
 await expect(page.locator('[data-bot-command]').first()).toHaveValue('rest');
 await page.locator('[data-bot-command]').first().selectOption('inherit');
 await page.locator('[data-command-day="6"]').click();
 await page.locator('[data-command="attack"]').click();
 for(let i=0;i<5;i++)await page.locator('#runOrders').click();
 await expect(page.locator('.ordersPanel')).toContainText('J6 : 5/5 tickets');
 await page.locator('#runOrders').click();
 await expect(page.locator('#status')).toContainText('0 bots');
 await page.locator('[data-command-day="7"]').click();
 await expect(page.locator('#runOrders')).toBeDisabled();
 expect(await page.evaluate(()=>localStorage.getItem('shadowreach.save.local'))).toBe('SAFE');
});
test('custom clan has eight obedient bots and incompatible orders wait',async({page})=>{
 await page.goto('/clan-bots-preview.html');
 await page.locator('#clanName').fill('Ordre des Étoiles');
 await page.getByRole('button',{name:'Créer mon clan'}).click();
 await page.locator('[data-tab="orders"]').click();
 await expect(page.locator('.orderRow')).toHaveCount(8);
 await page.locator('[data-command="attack"]').click();
 await page.locator('#runOrders').click();
 await expect(page.locator('#status')).toContainText('0 bots');
 await page.locator('[data-command="auto"]').click();
 await page.locator('#runOrders').click();
 await expect(page.locator('#status')).toContainText('8 bots');
});
